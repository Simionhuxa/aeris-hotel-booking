import { test, expect } from '@playwright/test';
import { PrismaClient } from '@prisma/client';
import { randomUUID } from 'node:crypto';
import { passwordHash } from '../server/security';
const db = new PrismaClient({ datasourceUrl: process.env.TEST_DATABASE_URL });
const email = `browser-${randomUUID()}@example.com`;
const adminEmail = `admin-${randomUUID()}@example.com`;
let reference = '';
test.beforeAll(async () => {
  for (const room of [{ id: 'forest-suite', name: 'Forest Suite', capacity: 2, area: 38, priceCents: 18500 }, { id: 'panorama-loft', name: 'Panorama Loft', capacity: 2, area: 52, priceCents: 27500 }, { id: 'summit-residence', name: 'Summit Residence', capacity: 4, area: 86, priceCents: 42000 }]) await db.room.upsert({ where: { id: room.id }, create: room, update: {} });
  await db.admin.create({ data: { email: adminEmail, passwordHash: passwordHash('browser-test-password') } });
});
test.afterAll(async () => {
  await db.booking.deleteMany({ where: { email } });
  await db.contactMessage.deleteMany({ where: { email } });
  await db.admin.deleteMany({ where: { email: adminEmail } });
  await db.$disconnect();
});
test('API errors, persisted booking, guest cancellation, contact and admin management', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('aeris-demo-stay-v1', JSON.stringify({ checkIn: '2091-06-10', checkOut: '2091-06-13', roomId: 'forest-suite', adults: 2, children: 0 })));
  await page.route('**/api/rooms', route => route.fulfill({ status: 503, json: { error: 'DEMO test unavailable' } }));
  await page.goto('/booking');
  await expect(page.getByRole('alert')).toContainText('DEMO test unavailable');
  await expect(page.getByRole('button', { name: 'Continue to your details' })).toBeDisabled();
  await page.unroute('**/api/rooms');
  await page.getByRole('button', { name: 'Retry rooms' }).click();
  await page.getByRole('button', { name: 'Continue to your details' }).click();
  await page.getByLabel('First name *', { exact: true }).fill('Demo');
  await page.getByLabel('Last name *', { exact: true }).fill('Browser');
  await page.getByLabel('Email address *', { exact: true }).fill(email);
  await page.getByLabel('Country / region *').selectOption('Ukraine');
  await page.getByLabel(/I accept the demo booking terms/).check();
  await page.getByRole('button', { name: 'Review your stay' }).click();
  await page.route('**/api/bookings', route => route.fulfill({ status: 409, json: { error: 'DEMO conflict. Choose another stay.' } }));
  await page.getByRole('button', { name: 'Create demo confirmation' }).click();
  await expect(page.getByRole('alert')).toContainText('DEMO conflict');
  await page.unroute('**/api/bookings');
  await page.getByRole('button', { name: 'Create demo confirmation' }).click();
  await expect(page).toHaveURL(/confirmation$/);
  await expect(page.getByRole('status')).toContainText('CONFIRMED');
  const saved = await db.booking.findFirstOrThrow({ where: { email } }); reference = saved.reference;
  expect(saved.totalCents).toBe(55500); expect(saved.demo).toBe(true);
  await page.getByRole('button', { name: 'Cancel DEMO booking' }).click();
  await expect(page.getByRole('status')).toContainText('CANCELLED');
  expect((await db.booking.findUniqueOrThrow({ where: { reference } })).status).toBe('CANCELLED');
  await page.goto('/contact');
  await page.getByLabel('First name *', { exact: true }).fill('Demo');
  await page.getByLabel('Last name *', { exact: true }).fill('Browser');
  await page.getByLabel('Email address *', { exact: true }).fill(email);
  await page.getByLabel('Your message *').fill('DEMO browser contact message');
  await page.getByLabel(/I agree to the privacy policy/).check();
  await page.route('**/api/contact', route => route.fulfill({ status: 500, json: { error: 'DEMO save failed' } }));
  await page.getByRole('button', { name: 'Send your note' }).click();
  await expect(page.getByRole('alert')).toContainText('DEMO save failed');
  await expect(page.getByLabel('Your message *')).toHaveValue('DEMO browser contact message');
  await page.unroute('**/api/contact');
  await page.getByRole('button', { name: 'Send your note' }).click();
  await expect(page.getByRole('status')).toContainText('DEMO message saved');
  await page.goto('/admin');
  await page.getByLabel('Email', { exact: true }).fill(adminEmail);
  await page.getByLabel('Password', { exact: true }).fill('browser-test-password');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await page.getByLabel('Search bookings').fill(email);
  await page.getByRole('button', { name: 'Search', exact: true }).click();
  await expect(page.locator('tbody')).toContainText(reference);
  await page.getByLabel('Booking status').selectOption('CANCELLED');
  await expect(page.locator('tbody')).toContainText(email);
  await page.getByRole('button', { name: 'Contact messages', exact: true }).click();
  await expect(page.locator('article')).toContainText('DEMO browser contact message');
  await page.getByRole('button', { name: 'Sign out', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Admin sign in' })).toBeVisible();
});
